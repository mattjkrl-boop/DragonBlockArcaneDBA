import java.util.Map;
import java.util.UUID;

/**
 * Entity Renderer for the Dread Gaze in Minecraft 26.2.
 *
 * Draws what Evil Dread shows the world: a shroud of darkness and smoke
 * material around the victim, and seven pairs of detailed red eyes
 * (textures/entity/dread_eye.png, generated by tools/gen_dread_textures.py)
 * floating in the dark around them. Every pair sits at a seeded angle,
 * distance, and height, fades in on its own delay after the anchor
 * spawns, breathes with a slow glow pulse, and blinks on its own seeded
 * schedule (staggered, so some eyes are always open while others are
 * shut).
 *
 * The shroud is emitted through MaterialEmitters as DARKNESS and SMOKE
 * material sampled on a shell around the victim. It draws no geometry.
 * The eyes are submitted as textured quad particle sprites on a layer
 * bound to the detailed eye texture, so this file writes no vertices.
 *
 * Positions anchor on the victim; the eye sprites face the viewer, so
 * from the victim's own view every pair stares straight at them, and
 * bystanders see the same ring watching the victim. Seeds come from the
 * victim's UUID, which every client shares, so all clients draw the
 * same ring and the ring survives anchor respawns. The envelope follows
 * the shared lifecycle rule: fade in over the anchor's first 16 ticks,
 * fade out over the effect's last 25.
 */
public class DreadGazeRenderer extends EntityRenderer<DreadGazeEntity, DreadGazeRenderer.GazeRenderState> {

    private static final Identifier EYE_TEXTURE = DragonBlockArcaneDBA.id("textures/entity/dread_eye.png");
    private static final int MAX_PAIRS = 7;
    private static final int FULL_BRIGHT = 0xF000F0;

    private final Map<UUID, ShroudEmitters> shroudEmitters = new HashMap<>();

    public DreadGazeRenderer(EntityRendererProvider.Context context) {
        super(context);
    }

    public static class GazeRenderState extends EntityRenderState {
        public float age = 0;
        public long seed = 0;
        public UUID anchorUuid;
        public int remaining = -1;
        public float victimWidth = 0.6f;
        public float victimHeight = 1.8f;
    }

    // 26.2 signature. No @Override: 26.3 added a float parameter to the vanilla method.
    public boolean shouldRender(DreadGazeEntity entity, net.minecraft.client.renderer.culling.Frustum frustum, double cameraX, double cameraY, double cameraZ) {
        return true;
    }

    // 26.3 signature: vanilla calls this overload on 26.3 and up.
    public boolean shouldRender(DreadGazeEntity entity, net.minecraft.client.renderer.culling.Frustum frustum, double cameraX, double cameraY, double cameraZ, float partialTick) {
        return true;
    }

    @Override
    public GazeRenderState createRenderState() {
        return new GazeRenderState();
    }

    @Override
    public void extractRenderState(DreadGazeEntity entity, GazeRenderState state, float partialTicks) {
        super.extractRenderState(entity, state, partialTicks);
        state.age = entity.tickCount + partialTicks;
        state.anchorUuid = entity.getUUID();
        // Ring identity comes from the victim, not the anchor, so a
        // replaced anchor redraws the same eyes in the same places.
        state.seed = entity.getUUID().getMostSignificantBits();
        state.remaining = -1;
        Entity target = entity.level().getEntity(entity.getVictimId());
        if (target instanceof LivingEntity victim) {
            state.seed = victim.getUUID().getMostSignificantBits();
            state.victimWidth = victim.getBbWidth();
            state.victimHeight = victim.getBbHeight();
            if (DbaEffects.EVIL_DREAD_HOLDER != null) {
                MobEffectInstance instance = victim.getEffect(DbaEffects.EVIL_DREAD_HOLDER);
                if (instance != null) state.remaining = instance.getDuration();
            }
        }
    }

    @Override
    public void submit(GazeRenderState state, PoseStack poseStack, SubmitNodeCollector collector, CameraRenderState cameraState) {
        float density = DbaEffectsConfig.effectDensity();
        float age = state.age;
        float fadeIn = FxEnvelope.smoothstep(Math.min(1.0f, age / 16.0f));
        float fadeOut = state.remaining >= 0
            ? FxEnvelope.smoothstep(Math.min(1.0f, state.remaining / 25.0f))
            : 1.0f;
        float env = fadeIn * fadeOut;
        if (density <= 0f || env <= 0.01f) {
            super.submit(state, poseStack, collector, cameraState);
            return;
        }
        final long seed = state.seed;

        ClientLevel level = Minecraft.getInstance().level;
        if (level != null && state.anchorUuid != null) {
            emitShroud(state, level, env);
        }

        if (cameraState.orientation == null || cameraState.pos == null) {
            super.submit(state, poseStack, collector, cameraState);
            return;
        }

        QuadParticleRenderState eyeParticles = new QuadParticleRenderState();
        SingleQuadParticle.Layer eyeLayer = new SingleQuadParticle.Layer(
            true, EYE_TEXTURE, SingleQuadParticle.Layer.TRANSLUCENT.pipeline());
        Vector3f right = new Vector3f(1.0f, 0.0f, 0.0f)
            .rotate(new Quaternionf(cameraState.orientation).conjugate());
        int pairs = Math.max(3, Math.round(MAX_PAIRS * Math.min(1.0f, density)));
        DeterministicRng rng = new DeterministicRng(seed ^ 0xE7E50L);
        for (int i = 0; i < MAX_PAIRS; i++) {
            // Fixed consumption order per pair, every frame: the ring is
            // a pure function of the victim seed and the pair index. The
            // stream matches the deprecated toolkit stream in behavior,
            // so the ring layout does not move when the reference leaves.
            float angleJitter = rng.signed() * 0.35f;
            float radius = rng.range(2.3f, 4.6f);
            float heightY = rng.range(0.35f, 2.6f);
            float pairWidth = rng.range(0.55f, 0.9f);
            float delay = 6.0f + i * 5.0f + rng.nextFloat() * 8.0f;
            float period = rng.range(53.0f, 120.0f);
            float phase = rng.nextFloat() * period;
            float pulsePhase = rng.nextFloat() * 6.2832f;
            float drift = rng.nextFloat() < 0.5f ? -1.0f : 1.0f;
            if (i >= pairs) continue;

            float appear = FxEnvelope.smoothstep(Math.max(0.0f, Math.min(1.0f, (age - delay) / 12.0f)));
            if (appear <= 0.01f) continue;

            float angle = (float) (i * (Math.PI * 2.0 / MAX_PAIRS)) + angleJitter + age * 0.005f * drift;
            float bob = (float) Math.sin(age * 0.07f + i * 1.7f) * 0.05f;
            float offX = (float) Math.cos(angle) * radius;
            float offZ = (float) Math.sin(angle) * radius;
            float offY = heightY + bob;

            // Blink: close over 2 ticks, hold a slit for 1, reopen over
            // 3. Each pair runs its own period and phase, so the ring
            // never blinks in unison. Quad particle sprites cannot
            // squash on one axis, so the same openness curve also
            // carries the closure through alpha and a slight scale.
            float cyc = (age + phase) % period;
            float openness;
            if (cyc < 2.0f) openness = 1.0f - 0.94f * FxEnvelope.smoothstep(cyc / 2.0f);
            else if (cyc < 3.0f) openness = 0.06f;
            else if (cyc < 6.0f) openness = 0.06f + 0.94f * FxEnvelope.smoothstep((cyc - 3.0f) / 3.0f);
            else openness = 1.0f;

            float pulse = 0.80f + 0.20f * (float) Math.sin(age * 0.13f + pulsePhase);
            final float alpha = env * appear * pulse * (0.10f + 0.90f * openness);
            final float eyeSize = pairWidth * 0.25f * (0.72f + 0.28f * openness);
            final float lateral = pairWidth * 0.27f;

            for (int side = -1; side <= 1; side += 2) {
                final float lat = lateral * side;
                double centerX = state.x + offX + right.x() * lat;
                double centerY = state.y + offY + right.y() * lat;
                double centerZ = state.z + offZ + right.z() * lat;
                // Halo pass first: a wide, faint copy so the eye blooms
                // against the dark, then the detailed core sprite.
                addEyeSprite(eyeParticles, eyeLayer, cameraState, centerX, centerY, centerZ,
                    eyeSize * 1.7f, 0.45f, 0.02f, 0.05f, alpha * 0.16f);
                addEyeSprite(eyeParticles, eyeLayer, cameraState, centerX, centerY, centerZ,
                    eyeSize, 1.0f, 1.0f, 1.0f, alpha * 0.95f);
            }
        }
        if (!eyeParticles.isEmpty()) {
            eyeParticles.submit(collector, cameraState);
        }

        super.submit(state, poseStack, collector, cameraState);
    }

    /**
     * The world shroud as material, not bands: DARKNESS and SMOKE
     * particles sampled on a shell around the victim and given a slow
     * tangential drift, in opposite directions per material, at the
     * same radius and height the old bands wrapped. Emission runs on
     * persistent per-anchor emitters so the rate stays frame-rate
     * independent and budgeted through the shared toolkit.
     */
    private void emitShroud(GazeRenderState state, ClientLevel level, float env) {
        float dist = MaterialEmitters.distanceScale(new Vec3(state.x, state.y, state.z));
        if (dist <= 0.01f) return;
        ShroudEmitters active = shroudEmitters.get(state.anchorUuid);
        if (active == null || active.level != level || active.seed != state.seed) {
            active = new ShroudEmitters(level, state.seed);
            shroudEmitters.put(state.anchorUuid, active);
        }
        active.update(state);
        active.tick(state.age, env * dist);

        long now = System.nanoTime();
        Iterator<Map.Entry<UUID, ShroudEmitters>> it = shroudEmitters.entrySet().iterator();
        while (it.hasNext()) {
            Map.Entry<UUID, ShroudEmitters> entry = it.next();
            if (entry.getValue() != active && now - entry.getValue().lastSeenNanos > 2_000_000_000L) {
                it.remove();
            }
        }
    }

    private static void addEyeSprite(QuadParticleRenderState particles, SingleQuadParticle.Layer layer,
                                     CameraRenderState cameraState,
                                     double worldX, double worldY, double worldZ,
                                     float size, float r, float g, float b, float a) {
        Quaternionf orientation = cameraState.orientation;
        particles.add(layer,
            (float) (worldX - cameraState.pos.x),
            (float) (worldY - cameraState.pos.y),
            (float) (worldZ - cameraState.pos.z),
            orientation.x, orientation.y, orientation.z, orientation.w,
            size, 0.0f, 1.0f, 0.0f, 1.0f,
            ARGB.colorFromFloat(a, r, g, b), FULL_BRIGHT);
    }

    /** Per-anchor continuous shroud emitters, created once per gaze. */
    private static final class ShroudEmitters {
        private final ClientLevel level;
        private final long seed;
        private final MaterialEmitters.Emitter darkness;
        private final MaterialEmitters.Emitter smoke;
        private Vec3 base = Vec3.ZERO;
        private float radius = 1.0f;
        private float top = 1.0f;
        private float lastAge = -1.0f;
        private long lastSeenNanos = System.nanoTime();

        private ShroudEmitters(ClientLevel level, long seed) {
            this.level = level;
            this.seed = seed;
            int seedBase = (int) (seed ^ (seed >>> 32));
            this.darkness = new MaterialEmitters.Emitter(level,
                MaterialEmitters.Preset.darkness(0x0D0017, 2.7f, seedBase, new Vec3(0.0, 0.020, 0.0), 0.010f),
                random -> sampleShell(random, 1.0f, 0.022f), 20.0f, 56);
            this.smoke = new MaterialEmitters.Emitter(level,
                MaterialEmitters.Preset.smoke(0x1A000A, 3.1f, seedBase ^ 0x5EED, new Vec3(0.0, 0.014, 0.0), 0.014f),
                random -> sampleShell(random, 1.22f, -0.016f), 11.0f, 32);
        }

        private void update(GazeRenderState state) {
            this.base = new Vec3(state.x, state.y, state.z);
            this.radius = state.victimWidth * 0.5f + 0.5f;
            this.top = Math.max(0.6f, state.victimHeight * 0.95f);
        }

        private MaterialEmitters.Sample sampleShell(RandomSource random, float radiusFactor, float tangentSpeed) {
            double angle = random.nextDouble() * Math.PI * 2.0;
            double r = radius * radiusFactor * (0.82 + random.nextDouble() * 0.38);
            Vec3 pos = new Vec3(
                base.x + Math.cos(angle) * r,
                base.y + random.nextDouble() * top,
                base.z + Math.sin(angle) * r);
            Vec3 tangent = new Vec3(-Math.sin(angle), 0.0, Math.cos(angle)).scale(tangentSpeed);
            return new MaterialEmitters.Sample(pos, tangent);
        }

        private void tick(float age, float envelope) {
            float delta;
            if (lastAge < 0.0f) {
                delta = 1.0f / 20.0f;
            } else {
                delta = (age - lastAge) / 20.0f;
                if (delta <= 0.0f || delta > 0.25f) delta = 1.0f / 20.0f;
            }
            lastAge = age;
            lastSeenNanos = System.nanoTime();
            darkness.tick(delta, envelope);
            smoke.tick(delta, envelope * 0.85f);
        }
    }

    /**
     * Splitmix stream with the same sequence the deprecated toolkit
     * produced, kept local so the eye ring layout, delays, periods, and
     * phases do not move when the toolkit reference leaves this file.
     * It is a random stream only; it draws nothing.
     */
    private static final class DeterministicRng {
        private long state;

        private DeterministicRng(long seed) {
            this.state = seed;
        }

        private long nextLong() {
            long z = (state += 0x9E3779B97F4A7C15L);
            z = (z ^ (z >>> 30)) * 0xBF58476D1CE4E5B9L;
            z = (z ^ (z >>> 27)) * 0x94D049BB133111EBL;
            return z ^ (z >>> 31);
        }

        private float nextFloat() {
            return (nextLong() >>> 40) * (1.0f / (1 << 24));
        }

        private float range(float a, float b) {
            return a + (b - a) * nextFloat();
        }

        private float signed() {
            return nextFloat() * 2.0f - 1.0f;
        }
    }
}
