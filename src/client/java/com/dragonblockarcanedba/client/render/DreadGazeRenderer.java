package com.dragonblockarcanedba.client.render;

import com.dragonblockarcanedba.DragonBlockArcaneDBA;
import com.dragonblockarcanedba.client.render.ki.BespokeGeometry;
import com.dragonblockarcanedba.client.render.ki.KiRenderHelper;
import com.dragonblockarcanedba.client.render.ki.LayeredRender;
import com.dragonblockarcanedba.config.DbaEffectsConfig;
import com.dragonblockarcanedba.effect.DbaEffects;
import com.dragonblockarcanedba.entity.DreadGazeEntity;
import com.dragonblockarcanedba.util.FxEnvelope;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.entity.state.EntityRenderState;
import net.minecraft.client.renderer.rendertype.RenderType;
import net.minecraft.client.renderer.rendertype.RenderTypes;
import net.minecraft.client.renderer.state.level.CameraRenderState;
import net.minecraft.resources.Identifier;
import net.minecraft.world.effect.MobEffectInstance;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.LivingEntity;
import org.joml.Matrix4f;
import org.joml.Quaternionf;

/**
 * Entity Renderer for the Dread Gaze in Minecraft 26.2.
 *
 * Draws what Evil Dread shows the world: a shroud of dark smoke bands
 * wrapped around the victim, and seven pairs of detailed red eyes
 * (textures/entity/dread_eye.png, generated by tools/gen_dread_textures.py)
 * floating in the dark around them. Every pair sits at a seeded angle,
 * distance, and height, fades in on its own delay after the anchor
 * spawns, breathes with a slow glow pulse, and blinks on its own seeded
 * schedule (staggered, so some eyes are always open while others are
 * shut). The blink is a vertical squash of the billboard, eyelid style.
 *
 * Positions anchor on the victim; the eye planes billboard to the
 * viewer, so from the victim's own view every pair stares straight at
 * them, and bystanders see the same ring watching the victim. Seeds
 * come from the victim's UUID, which every client shares, so all
 * clients draw the same ring and the ring survives anchor respawns.
 * The envelope follows the shared lifecycle rule: fade in over the
 * anchor's first 16 ticks, fade out over the effect's last 25.
 */
public class DreadGazeRenderer extends EntityRenderer<DreadGazeEntity, DreadGazeRenderer.GazeRenderState> {

    private static final Identifier EYE_TEXTURE = DragonBlockArcaneDBA.id("textures/entity/dread_eye.png");
    private static final int MAX_PAIRS = 7;

    public DreadGazeRenderer(EntityRendererProvider.Context context) {
        super(context);
    }

    public static class GazeRenderState extends EntityRenderState {
        public float age = 0;
        public long seed = 0;
        public int remaining = -1;
        public float victimWidth = 0.6f;
        public float victimHeight = 1.8f;
    }

    // 26.2 signature. No @Override: 26.3 added a float parameter to the vanilla method.
    public boolean shouldRender(DreadGazeEntity entity, net.minecraft.client.renderer.culling.Frustum frustum, double cameraX, double cameraY, double cameraZ) {
        return true;
    }

    // 26.3 signature: vanilla calls this overload on 26.3 and up.
    public boolean shouldRender(DreadGazeEntity entity, net.minecraft.client.renderer.culling.Frustum frustum, double cameraX, double cameraY, double cameraZ, float partialTick) {
        return true;
    }

    @Override
    public GazeRenderState createRenderState() {
        return new GazeRenderState();
    }

    @Override
    public void extractRenderState(DreadGazeEntity entity, GazeRenderState state, float partialTicks) {
        super.extractRenderState(entity, state, partialTicks);
        state.age = entity.tickCount + partialTicks;
        // Ring identity comes from the victim, not the anchor, so a
        // replaced anchor redraws the same eyes in the same places.
        state.seed = entity.getUUID().getMostSignificantBits();
        state.remaining = -1;
        Entity target = entity.level().getEntity(entity.getVictimId());
        if (target instanceof LivingEntity victim) {
            state.seed = victim.getUUID().getMostSignificantBits();
            state.victimWidth = victim.getBbWidth();
            state.victimHeight = victim.getBbHeight();
            if (DbaEffects.EVIL_DREAD_HOLDER != null) {
                MobEffectInstance instance = victim.getEffect(DbaEffects.EVIL_DREAD_HOLDER);
                if (instance != null) state.remaining = instance.getDuration();
            }
        }
    }

    @Override
    public void submit(GazeRenderState state, PoseStack poseStack, SubmitNodeCollector collector, CameraRenderState cameraState) {
        float density = DbaEffectsConfig.effectDensity();
        float age = state.age;
        float fadeIn = FxEnvelope.smoothstep(Math.min(1.0f, age / 16.0f));
        float fadeOut = state.remaining >= 0
            ? FxEnvelope.smoothstep(Math.min(1.0f, state.remaining / 25.0f))
            : 1.0f;
        float env = fadeIn * fadeOut;
        if (density <= 0f || env <= 0.01f) {
            super.submit(state, poseStack, collector, cameraState);
            return;
        }
        final float ds = LayeredRender.distScale(cameraState, state.x, state.y, state.z);
        final long seed = state.seed;

        // The shroud: two counter-turning bands of near-black smoke
        // around the victim's body, the darkness made visible to
        // everyone watching. Bespoke toolkit geometry, house pattern.
        final float shroudR = state.victimWidth * 0.5f + 0.5f;
        final float shroudTop = Math.max(0.6f, state.victimHeight * 0.95f);
        final float shroudEnv = env;
        collector.submitCustomGeometry(poseStack, KiRenderHelper.kiRenderType(), (pose, buffer) -> {
            BespokeGeometry.brokenVortexBand(pose, buffer, seed ^ 0xD12E1L,
                shroudR, 0.05f, shroudTop, age * 0.06f,
                0.05f, 0.0f, 0.09f, 0.34f * shroudEnv, ds);
            BespokeGeometry.brokenVortexBand(pose, buffer, seed ^ 0xD12E2L,
                shroudR * 1.25f, 0.02f, shroudTop * 0.8f, -age * 0.045f,
                0.10f, 0.0f, 0.04f, 0.26f * shroudEnv, ds);
        });

        if (cameraState.orientation == null) {
            super.submit(state, poseStack, collector, cameraState);
            return;
        }
        RenderType eyeType = RenderTypes.entityTranslucentEmissive(EYE_TEXTURE);
        int pairs = Math.max(3, Math.round(MAX_PAIRS * Math.min(1.0f, density)));
        BespokeGeometry.Rng rng = new BespokeGeometry.Rng(seed ^ 0xE7E50L);
        for (int i = 0; i < MAX_PAIRS; i++) {
            // Fixed consumption order per pair, every frame: the ring is
            // a pure function of the victim seed and the pair index.
            float angleJitter = rng.signed() * 0.35f;
            float radius = rng.range(2.3f, 4.6f);
            float heightY = rng.range(0.35f, 2.6f);
            float pairWidth = rng.range(0.55f, 0.9f);
            float delay = 6.0f + i * 5.0f + rng.nextFloat() * 8.0f;
            float period = rng.range(53.0f, 120.0f);
            float phase = rng.nextFloat() * period;
            float pulsePhase = rng.nextFloat() * 6.2832f;
            float drift = rng.nextFloat() < 0.5f ? -1.0f : 1.0f;
            if (i >= pairs) continue;

            float appear = FxEnvelope.smoothstep(Math.max(0.0f, Math.min(1.0f, (age - delay) / 12.0f)));
            if (appear <= 0.01f) continue;

            float angle = (float) (i * (Math.PI * 2.0 / MAX_PAIRS)) + angleJitter + age * 0.005f * drift;
            float bob = (float) Math.sin(age * 0.07f + i * 1.7f) * 0.05f;
            float offX = (float) Math.cos(angle) * radius;
            float offZ = (float) Math.sin(angle) * radius;
            float offY = heightY + bob;

            // Blink: close over 2 ticks, hold a slit for 1, reopen over
            // 3. Each pair runs its own period and phase, so the ring
            // never blinks in unison.
            float cyc = (age + phase) % period;
            float openness;
            if (cyc < 2.0f) openness = 1.0f - 0.94f * FxEnvelope.smoothstep(cyc / 2.0f);
            else if (cyc < 3.0f) openness = 0.06f;
            else if (cyc < 6.0f) openness = 0.06f + 0.94f * FxEnvelope.smoothstep((cyc - 3.0f) / 3.0f);
            else openness = 1.0f;

            float pulse = 0.80f + 0.20f * (float) Math.sin(age * 0.13f + pulsePhase);
            final float alpha = env * appear * pulse;
            final float eyeHalfW = pairWidth * 0.25f;
            final float eyeHalfH = eyeHalfW * 0.80f * openness;
            final float lateral = pairWidth * 0.27f;

            for (int side = -1; side <= 1; side += 2) {
                final float lat = lateral * side;
                poseStack.pushPose();
                poseStack.translate(offX, offY, offZ);
                poseStack.mulPose(new Matrix4f().rotation(new Quaternionf(cameraState.orientation).conjugate()));
                poseStack.translate(lat, 0, 0);
                collector.submitCustomGeometry(poseStack, eyeType, (pose, buffer) -> {
                    // Halo pass first: a wide, faint copy so the eye
                    // blooms against the dark, then the detailed core.
                    eyeQuad(pose, buffer, eyeHalfW * 1.7f, eyeHalfH * 1.7f,
                        0.45f, 0.02f, 0.05f, alpha * 0.16f);
                    eyeQuad(pose, buffer, eyeHalfW, eyeHalfH,
                        1.0f, 1.0f, 1.0f, alpha * 0.95f);
                });
                poseStack.popPose();
            }
        }

        super.submit(state, poseStack, collector, cameraState);
    }

    /**
     * One textured eye quad centered on the local origin, emitted with
     * both windings so it reads from either side of the billboard plane.
     * The texture carries the detail (iris, slit pupil, glint); the
     * vertex color and alpha carry the glow tint and the envelope.
     */
    private static void eyeQuad(PoseStack.Pose pose, VertexConsumer buffer,
                                float halfW, float halfH,
                                float r, float g, float b, float a) {
        Matrix4f mat = pose.pose();
        // Front, facing the viewer.
        KiRenderHelper.vertex(buffer, mat, pose, -halfW, -halfH, 0, r, g, b, a, 0, 1, 0, 0, 1);
        KiRenderHelper.vertex(buffer, mat, pose, halfW, -halfH, 0, r, g, b, a, 1, 1, 0, 0, 1);
        KiRenderHelper.vertex(buffer, mat, pose, halfW, halfH, 0, r, g, b, a, 1, 0, 0, 0, 1);
        KiRenderHelper.vertex(buffer, mat, pose, -halfW, halfH, 0, r, g, b, a, 0, 0, 0, 0, 1);
        // Back, reversed winding.
        KiRenderHelper.vertex(buffer, mat, pose, -halfW, -halfH, 0, r, g, b, a, 0, 1, 0, 0, -1);
        KiRenderHelper.vertex(buffer, mat, pose, -halfW, halfH, 0, r, g, b, a, 0, 0, 0, 0, -1);
        KiRenderHelper.vertex(buffer, mat, pose, halfW, halfH, 0, r, g, b, a, 1, 0, 0, 0, -1);
        KiRenderHelper.vertex(buffer, mat, pose, halfW, -halfH, 0, r, g, b, a, 1, 1, 0, 0, -1);
    }
}
